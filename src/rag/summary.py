"""Build the final comparison tables from saved results.

python -m rag.summary --results results
Reads <benchmark>/report.json (BM25, dense, hybrid, hybrid + rerank), <benchmark>/decomp_eval.json
and <benchmark>/qa/*.jsonl, and writes SUMMARY.md and summary.json. No models or API calls.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .metrics import METRICS, paired_bootstrap

ORDER = ["bm25", "dense", "hybrid", "hybrid_rerank", "hybrid_rerank_decomp"]
BENCHMARKS = ["hotpotqa", "qasper"]


def load_per_question(results: Path, benchmark: str) -> dict[str, dict[str, dict]]:
    """system -> qid -> per-question retrieval metrics (eval split)."""
    rep = json.loads((results / benchmark / "report.json").read_text())["per_question"]
    out = {s: {e["qid"]: e for e in rep[f"{s}/eval"]} for s in ORDER[:4]}
    dec = json.loads((results / benchmark / "decomp_eval.json").read_text())["per_question"]
    out["hybrid_rerank_decomp"] = {e["qid"]: e for e in dec["hybrid_rerank_decomp/eval"]}
    return out


def load_retrieval_summary(results: Path, benchmark: str) -> dict[str, dict]:
    rep = json.loads((results / benchmark / "report.json").read_text())["results"]
    out = {s: rep[f"{s}/eval"] for s in ORDER[:4]}
    dec = json.loads((results / benchmark / "decomp_eval.json").read_text())["results"]
    out["hybrid_rerank_decomp"] = dec["hybrid_rerank_decomp/eval"]
    return out


def load_qa(results: Path, benchmark: str) -> tuple[dict[str, dict], dict[str, dict[str, dict]]]:
    summaries, rows = {}, {}
    for s in ORDER:
        d = results / benchmark / "qa"
        summaries[s] = json.loads((d / f"{s}_eval_summary.json").read_text())
        rows[s] = {r["qid"]: r for r in map(json.loads, (d / f"{s}_eval.jsonl").read_text().splitlines())}
    return summaries, rows


def paired_table(data: dict[str, dict[str, dict]], metrics: tuple[str, ...]) -> dict[str, dict]:
    out = {}
    for a, b in zip(ORDER, ORDER[1:]):
        qids = sorted(data[a])
        assert set(qids) == set(data[b]), "systems must cover the same questions"
        out[f"{a} -> {b}"] = {m: paired_bootstrap([data[a][q] for q in qids],
                                                  [data[b][q] for q in qids], m) for m in metrics}
    return out


def fmt_diff(r: dict) -> str:
    return f"{r['diff']:+.3f} [{r['ci95_low']:+.3f}, {r['ci95_high']:+.3f}], p={r['p']:.3f}"


def build(results: str | Path) -> tuple[str, dict]:
    results = Path(results)
    md = ["# Final results (eval split, 500 questions per benchmark, k=5)\n",
          "Means with 95% bootstrap CIs over questions. Differences are second minus first system on "
          "the same questions, with a paired bootstrap CI and two-sided p-value. Generated by "
          "`python -m rag.summary`; do not edit by hand.\n"]
    out: dict = {}
    for b in BENCHMARKS:
        ret, qa = load_retrieval_summary(results, b), None
        qa_sum, qa_rows = load_qa(results, b)
        pq = load_per_question(results, b)
        md += [f"\n## {b}\n", "### Retrieval\n",
               "| system | Recall@5 | Complete Recall@5 | MRR@5 |\n|---|---|---|---|"]
        for s in ORDER:
            r = ret[s]
            cell = lambda m: f"{r[m]:.3f} [{r['ci95'][m][0]:.3f}, {r['ci95'][m][1]:.3f}]"
            md.append(f"| {s} | {cell('recall')} | {cell('complete_recall')} | {cell('mrr')} |")
        qtypes = sorted(ret["bm25"]["by_qtype"])
        if qtypes:
            md += ["\nComplete Recall@5 by question type:\n",
                   "| system | " + " | ".join(qtypes) + " |\n|---|" + "---|" * len(qtypes)]
            for s in ORDER:
                md.append(f"| {s} | " + " | ".join(
                    f"{ret[s]['by_qtype'][t]['complete_recall']:.3f} (n={ret[s]['by_qtype'][t]['n']})"
                    for t in qtypes) + " |")
        md += ["\n### Answer quality (generated answers scored against gold)\n",
               "| system | EM | F1 | answers with a valid citation | citing a gold chunk |\n|---|---|---|---|---|"]
        for s in ORDER:
            q = qa_sum[s]
            md.append(f"| {s} | {q['em']:.3f} [{q['em_ci95'][0]:.3f}, {q['em_ci95'][1]:.3f}] | "
                      f"{q['f1']:.3f} [{q['f1_ci95'][0]:.3f}, {q['f1_ci95'][1]:.3f}] | "
                      f"{q['pct_with_valid_citation']:.1f}% | {q['pct_citing_gold_chunk']:.1f}% |")
        pr, pa = paired_table(pq, METRICS), paired_table(qa_rows, ("em", "f1"))
        md += ["\n### Paired differences between consecutive systems\n",
               "| comparison | Recall@5 | Complete Recall@5 | MRR@5 | answer F1 |\n|---|---|---|---|---|"]
        for pair in pr:
            md.append(f"| {pair} | {fmt_diff(pr[pair]['recall'])} | {fmt_diff(pr[pair]['complete_recall'])} | "
                      f"{fmt_diff(pr[pair]['mrr'])} | {fmt_diff(pa[pair]['f1'])} |")
        out[b] = {"retrieval": ret, "qa": qa_sum, "paired_retrieval": pr, "paired_qa": pa}
    return "\n".join(md) + "\n", out


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="rag.summary")
    p.add_argument("--results", default="results")
    a = p.parse_args(argv)
    md, data = build(a.results)
    (Path(a.results) / "SUMMARY.md").write_text(md)
    (Path(a.results) / "summary.json").write_text(json.dumps(data, indent=1))
    print(md)


if __name__ == "__main__":
    main()
